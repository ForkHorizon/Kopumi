// Pasteboard watcher (capture) and paster (put a clip back and paste it).
import AppKit
import CryptoKit

/// Polls the pasteboard and saves every new copy. Fast and dumb: no AI here.
@MainActor
final class Watcher {
  static let maxBlobBytes = 20_000_000

  /// nspasteboard.org conventions used by password managers.
  static let skipTypes: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"),
  ]
  static let ignoredApps: Set<String> = [
    "com.1password.1password", "com.agilebits.onepassword7", "com.apple.keychainaccess",
    "com.apple.Passwords", "com.bitwarden.desktop",
  ]

  let store: Store
  var onChange: () -> Void = {}
  private var lastCount = NSPasteboard.general.changeCount

  init(store: Store) { self.store = store }

  func start() {
    // The run loop retains scheduled timers, so they need no stored reference.
    Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated { self?.tick() }
    }
    Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated { try? self?.store.prune(maxItems: Prefs.maxItems) }
    }
  }

  private func tick() {
    let pb = NSPasteboard.general
    guard pb.changeCount != lastCount else { return }
    lastCount = pb.changeCount  // also while paused, so resuming doesn't grab an old copy
    guard !Prefs.isPaused, pb.changeCount != Paster.lastWrite,  // our own paste-from-history
      let clip = Self.capture(
        pb, sourceApp: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    else { return }
    do {
      try store.upsert(clip)
      try store.prune(maxItems: Prefs.maxItems)
      onChange()
    } catch { print("store:", error) }
  }

  /// Double Cmd+C: append the text just copied to the clip before it, and put the result on the
  /// pasteboard so the next paste gives both.
  func appendLatest() {
    Task {
      try? await Task.sleep(for: .milliseconds(150))  // let the second copy land
      tick()
      guard let recent = try? store.recent(limit: 2), recent.count == 2,
        let merged = Self.appended(recent[1], to: recent[0]), let text = merged.text
      else { return }
      do {
        try store.upsert(merged)
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        Paster.lastWrite = pb.changeCount
        lastCount = pb.changeCount
        onChange()
      } catch { print("append:", error) }
    }
  }

  /// `previous` + newline + `new`; nil for secrets, images, files, or a repeat of the same text.
  static func appended(_ previous: Clip, to new: Clip) -> NewClip? {
    let nonText: Set<ClipKind> = [.image, .files]
    guard !previous.sensitive, !new.sensitive, !nonText.contains(previous.kind),
      !nonText.contains(new.kind), let a = previous.text, let b = new.text, a != b
    else { return nil }
    let text = a + "\n" + b
    return NewClip(
      kind: classify(text).kind, text: text, sourceApp: new.sourceApp,
      contentHash: hash("text", Data(text.utf8)), derivedFrom: previous.id)
  }

  /// Pasteboard → NewClip, or nil if it must not be stored.
  static func capture(_ pb: NSPasteboard, sourceApp: String?) -> NewClip? {
    guard let types = pb.types, skipTypes.isDisjoint(with: types) else { return nil }
    if let app = sourceApp, ignoredApps.contains(app) || Prefs.ignoredApps.contains(app) {
      return nil
    }

    if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
      as? [URL],
      !urls.isEmpty
    {
      let paths = urls.map(\.path).joined(separator: "\n")
      return NewClip(
        kind: .files, text: paths, sourceApp: sourceApp, meta: ["count": "\(urls.count)"],
        contentHash: hash("files", Data(paths.utf8)))
    }
    if let text = pb.string(forType: .string), !text.isEmpty {
      let secret = isSensitive(text)
      let c = classify(text, sourceApp: sourceApp)
      let rich: [Blob] =
        secret
        ? []
        : [NSPasteboard.PasteboardType.rtf, .html].compactMap { t in
          pb.data(forType: t).flatMap { $0.count < maxBlobBytes ? (t.rawValue, $0) : nil }
        }
      return NewClip(
        kind: c.kind, text: text, sourceApp: sourceApp, meta: c.meta,
        contentHash: hash("text", Data(text.utf8)), sensitive: secret, blobs: rich)
    }
    for t in [NSPasteboard.PasteboardType.png, .tiff] {
      if let img = pb.data(forType: t), img.count < maxBlobBytes {
        return NewClip(
          kind: .image, text: nil, sourceApp: sourceApp,
          contentHash: hash("image", img), blobs: [(t.rawValue, img)])
      }
    }
    return nil
  }

  static func hash(_ prefix: String, _ data: Data) -> String {
    prefix + ":" + SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
  }
}

/// Puts a clip back on the pasteboard and pastes it into the frontmost app.
@MainActor
enum Paster {
  /// changeCount of our own last write, so the Watcher doesn't re-capture it.
  static var lastWrite = -1

  /// `target` = bundle id of the app receiving the paste; drives context-aware formatting.
  static func paste(_ clip: Clip, blobs: [Blob], target: String? = nil, forcePlain: Bool = false) {
    let style = pasteStyle(for: target, forcePlain: forcePlain)
    let pb = NSPasteboard.general
    pb.clearContents()
    if clip.kind == .files, style == .asCopied, let paths = clip.text {
      pb.writeObjects(paths.split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) })
    } else {
      let item = NSPasteboardItem()
      if style == .asCopied || clip.kind == .image {
        for b in blobs { item.setData(b.data, forType: .init(b.uti)) }
      }
      if let t = clip.text { item.setString(pasteText(t, style), forType: .string) }
      pb.writeObjects([item])
    }
    lastWrite = pb.changeCount
    Task {
      try? await Task.sleep(for: .milliseconds(80))  // let the menu close and focus return
      KeyTap.postCmdV()
    }
  }
}
